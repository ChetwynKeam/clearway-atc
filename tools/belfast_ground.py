# Belfast: Aldergrove (EGAA) and George Best City (EGAC) aerodromes in one metre frame (origin: the EGAA ARP) from
# OpenStreetMap, the runway thresholds from AIP AD 2-EGAA-2-1 and AD 2-EGAC-2-1 -> src/airports/egaa-ground.js
# usage: python3 tools/belfast_ground.py osm/egaa.json osm/egac.json src/airports/egaa-ground.js
# Each aerodrome is built by tools/belfast_ground_one.py (the Bristol generator, with a straight link from each holding
# position to the runway where OSM has none, and the taxiway ends snapped together), then EGAC is shifted into the EGAA frame.
import json, math, subprocess, sys, os, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
EGAA_OSM, EGAC_OSM, OUT = sys.argv[1:4]
A = (54 + 39/60 + 27/3600, -(6 + 12/60 + 57/3600)); C = (54 + 37/60 + 5/3600, -(5 + 52/60 + 21/3600))
DX, DY = (C[1] - A[1])*60*1852*math.cos(math.radians(A[0])), (C[0] - A[0])*60*1852
r1 = lambda v: round(v, 1)
def run(af, osm):
    f = tempfile.mktemp(suffix='.json'); subprocess.run([sys.executable, os.path.join(HERE, 'belfast_ground_one.py'), af, osm, f], check=True, stdout=subprocess.DEVNULL); return json.load(open(f))
a, c = run('EGAA', EGAA_OSM), run('EGAC', EGAC_OSM)
sh = lambda p: [r1(p[0] + DX), r1(p[1] + DY)]
shp = lambda pts: [sh(p) for p in pts]
for r in a['runways']: r['ap'] = 'EGAA'
for r in c['runways']: r['ap'] = 'EGAC'; r['a'] = sh(r['a']); r['b'] = sh(r['b'])
c['nodes'] = [[n[0], *sh(n[1:])] for n in c['nodes']]
c['rnodes'] = [[n[0], *sh(n[1:])] for n in c['rnodes']]
c['edges'] = [[e[0], e[1], e[2], shp(e[3])] + e[4:] for e in c['edges']]
for g in c['gates']:
    g[0] = 'C' + g[0]; g[2] = sh(g[2])
    if g[5]: g[5] = shp(g[5])
    if len(g) > 6 and g[6]: g[6] = [g[6][0], shp(g[6][1])]
c['aprons'] = [shp(p) for p in c['aprons']]
for b in c['buildings']: b['pts'] = shp(b['pts'])
ren = lambda d: {k + '@C': v for k, v in d.items()}
c['holds'], c['hlink'], c['fil'] = ren(c['holds']), ren(c['hlink']), ren(c['fil'])
out = {'runways': a['runways'] + c['runways'], 'nodes': a['nodes'] + c['nodes'], 'edges': a['edges'] + c['edges'], 'rnodes': a['rnodes'] + c['rnodes'],
       'holds': {**a['holds'], **c['holds']}, 'hlink': {**a['hlink'], **c['hlink']}, 'fil': {**a['fil'], **c['fil']}, 'hs': {**a['hs'], **c['hs']},
       'gates': a['gates'] + c['gates'], 'ihps': a['ihps'] + c['ihps'], 'aprons': a['aprons'] + c['aprons'], 'buildings': a['buildings'] + c['buildings'],
       'origin': {'EGAC': [r1(DX), r1(DY)]}}
with open(OUT, 'w') as fo:
    fo.write('''// ═════════════════════════ Belfast (EGAA + EGAC): aerodrome layouts ═════════════════════════
// Generated by tools/belfast_ground.py from OpenStreetMap with the runway thresholds from the AIPs (AD 2-EGAA-2-1,
// AD 2-EGAC-2-1). Positions are metres east and north of the Belfast Aldergrove ARP (54°39'27"N 006°12'57"W); Belfast City
// is the same frame (its ARP is at origin.EGAC). Runways carry 'ap' (their aerodrome); City's holding points are keyed
// with an @C suffix and its stands are numbered C1 to C10. Layout otherwise as eggd-ground.js.
const EGAA_GROUND = ''')
    fo.write(json.dumps(out, separators=(',', ':')))
    fo.write(';\nif (typeof module !== \'undefined\') module.exports = EGAA_GROUND;\n')
print('runways', [r['id'] for r in out['runways']], 'nodes', len(out['nodes']), 'edges', len(out['edges']), 'holds', len(out['holds']), 'gates', len(out['gates']))
