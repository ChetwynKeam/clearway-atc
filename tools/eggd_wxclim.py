"""Bristol (EGGD) weather climatology for the "Typical" weather: src/airports/eggd-wx.js.

Downloads every EGGD METAR for 2019-2024 from the Iowa Environmental Mesonet archive, keeps the daytime ones (06-21Z,
when the traffic flies), cleans them for the simulator's METAR parser (AUTO, NCD/NSC, missing-group slashes, recent
weather, windshear and trends removed) and draws 150 at random for each month (fixed seed, so a rerun gives the same
file). The game picks one for the current month when a session starts.

usage: python3 tools/eggd_wxclim.py
"""
import csv, io, json, pathlib, random, re, urllib.request, collections

ROOT = pathlib.Path(__file__).resolve().parent.parent
URL = ('https://mesonet.agron.iastate.edu/cgi-bin/request/asos.py?station=EGGD&data=metar&year1={y}&month1=1&day1=1'
       '&year2={y1}&month2=1&day2=1&tz=Etc/UTC&format=onlycomma&latlon=no&missing=M&trace=T&direct=no&report_type=3&report_type=4')
YEARS = range(2019, 2025)
PER_MONTH = 150


def clean(m):
    m = re.sub(r'^EGGD ', '', m.split(' RMK ')[0])
    out = []
    for tok in m.split():
        if tok in ('AUTO', 'COR', 'NOSIG', 'NCD', 'NSC'):
            continue
        if re.fullmatch(r'/+(CB|TCU)?', tok):
            continue
        tok = re.sub(r'(\d{3})/+$', r'\1', tok)          # BKN020/// -> BKN020
        if tok.startswith(('RE', 'WS')) or tok in ('TEMPO', 'BECMG'):
            break
        out.append(tok)
    return ' '.join(out)


def main():
    rows = []
    for y in YEARS:
        with urllib.request.urlopen(URL.format(y=y, y1=y + 1), timeout=180) as r:
            for row in csv.DictReader(io.StringIO(r.read().decode())):
                m = row['metar']
                if m.startswith('EGGD') and 'NIL' not in m:
                    rows.append((int(row['valid'][5:7]), int(row['valid'][11:13]), m))
    by = collections.defaultdict(list)
    for mo, hh, m in rows:
        if 6 <= hh <= 21:
            by[mo].append(clean(m))
    random.seed(7)
    months = [random.sample(by[mo], PER_MONTH) for mo in range(1, 13)]
    js = ('// Bristol (EGGD) weather climatology: 1,800 real METARs, 150 for each month, drawn at random from every daytime (06-22Z)\n'
          '// report in 2019-2024 (Iowa Environmental Mesonet ASOS/METAR archive). The "Typical Bristol" weather picks one for the\n'
          '// session\'s month, so the wind, cloud, rain and fog come up as often as they really do on Broadfield Down.\n'
          '// Cleaned for the parser: AUTO, NCD, missing-group slashes, recent weather and trends removed.\n'
          '// Generated by tools/eggd_wxclim.py.\n'
          'const EGGD_WXCLIM = ' + json.dumps({'src': 'Iowa Environmental Mesonet METAR archive, EGGD 2019-2024', 'n': len(rows), 'm': months},
                                              separators=(',', ':')) + ';\n')
    (ROOT / 'src' / 'airports' / 'eggd-wx.js').write_text(js)
    print(len(rows), 'reports;', len(js), 'bytes')


if __name__ == '__main__':
    main()
